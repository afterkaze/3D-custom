const { contextBridge, ipcRenderer } = require('electron');

const call = async (ch, ...args) => {
  const r = await ipcRenderer.invoke(ch, ...args);
  if (!r.ok) throw new Error(r.error);
  return r.value;
};

contextBridge.exposeInMainWorld('api', {
  leiaDiagnostics: () => call('leia:diagnostics'),
  leiaStatus: () => call('leia:status'),
  leiaEnable: enabled => call('leia:enable', enabled),
  leiaQuality: quality => call('leia:quality', quality),
  leiaLayout: layout => call('leia:layout', layout),
  leiaSnapshot: snapshot => ipcRenderer.send('leia:snapshot', snapshot),
  onLeiaStatus: callback => ipcRenderer.on('leia:status',(_,status)=>callback(status)),
  getConfig: () => call('config:get'),
  setConfig: cfg => call('config:set', cfg),
  scan: withReport => call('library:scan', withReport),
  launch: (id, options) => call('game:launch', id, options),
  quitGame: () => call('game:quit'),
  runningGames: () => call('game:running'),
  screenshots: id => call('game:screenshots', id),
  chooseGameExecutable: id => call('game:chooseExecutable', id),
  openGameFolder: id => call('game:openFolder', id),
  recompContextMenu: () => call('library:recompMenu'),
  gameContextMenu: id => call('game:contextMenu', id),
  setSystemGamesHidden: options => call('library:setSystemGamesHidden', options),
  screenshotContextMenu: id => call('game:screenshotMenu', id),
  setMetadata: options => call('game:setMetadata', options),
  gameSources: gameId => call('game:sources', gameId),
  setDetailsSource: options => call('game:setDetailsSource', options),
  setArtSource: options => call('game:setArtSource', options),
  openSource: target => call('game:openSource', target),
  setHidden: options => call('game:setHidden', options),
  setFavorite: options => call('game:setFavorite', options),
  gameOrders: () => call('library:gameOrders'),
  saveGameOrder: order => call('library:saveGameOrder',order),
  libraryUi: () => call('library:ui'),
  saveLibraryUi: patch => call('library:saveUi', patch),
  onGameStarted: fn => ipcRenderer.on('game:started', (_e, p) => fn(p)),
  onGameEnded: fn => ipcRenderer.on('game:ended', (_e, p) => fn(p)),
  gameAdd: options => call('game:add', options),
  gameRemove: id => call('game:remove', id),
  gameList: () => call('game:list'),
  gameSetShell: options => call('game:setShell', options),
  gameSetEmulator: options => call('game:setEmulator', options),
  fetchArt: (sys, base, options) => call('art:fetch', sys, base, options),
  artStart: options => call('art:start', options),
  artStatus: () => call('art:status'),
  artCancel: () => call('art:cancel'),
  artOpenFolder: () => call('art:openFolder'),
  artImport: options => call('art:import', options),
  artSources: () => call('art:sources'),
  artCandidates: options => call('art:candidates', options),
  artFindManuals: () => call('art:findManuals'),
  artChoose: options => call('art:choose', options),
  artSetScreenScraper: details => call('art:setScreenScraper', details),
  onArtProgress: fn => ipcRenderer.on('art:progress', (_e, p) => fn(p)),
  onArtMedia: fn => ipcRenderer.on('art:media', (_e, p) => fn(p)),
  onLibraryInfo: fn => ipcRenderer.on('library:info', (_e, p) => fn(p)),
  emuList: () => call('emu:list'),
  emuCheck: id => call('emu:check', id),
  emuInstall: id => call('emu:install', id),
  emuUninstall: id => call('emu:uninstall', id),
  emuOpenFolder: id => call('emu:openFolder', id),
  emuPickExe: id => call('emu:pickExe', id),
  emuAddCustom: opts => call('emu:addCustom', opts),
  emuSetSource: opts => call('emu:setSource', opts),
  emuTestSource: opts => call('emu:testSource', opts),
  emuAddRepo: opts => call('emu:addRepo', opts),
  emuRemove: id => call('emu:remove', id),
  pickFolder: title => call('dialog:folder', title),
  openManual: p => call('manual:open', p),
  manualUrl: p => call('manual:url', p),
  onProgress: fn => ipcRenderer.on('emu:progress', (_e, p) => fn(p)),
  onToast: fn => ipcRenderer.on('toast', (_e, m) => fn(m)),
  appVersion: () => call('app:version'),
  appCheckUpdate: () => call('app:checkUpdate'),
  appInstallUpdate: () => call('app:installUpdate'),
  appOpenRelease: url => call('app:openRelease', url),
  onAppUpdateProgress: fn => ipcRenderer.on('app:updateProgress', (_e, p) => fn(p)),
});
